def build_stage3_start():
    env1 = (
        HelicopterEnvStage1Distill(
            teacher_model_path=None,
            training_mode=False,
        )
    )

    obs1, info1 = (
        env1.reset()
    )

    fdm = get_fdm(
        env1
    )

    active_fdm_id = id(
        fdm
    )

    mission_heading = heading_rad(
        fdm
    )

    dt1 = env_control_dt(
        env1
    )

    stable_time = 0.0

    for _ in range(
        int(
            STAGE1_MAX_TIME
            /
            dt1
        )
    ):
        action1, _ = (
            stage1_model.predict(
                obs1,
                deterministic=True,
            )
        )

        (
            obs1,
            _,
            terminated,
            truncated,
            info1,
        ) = env1.step(
            action1
        )

        altitude = info_float(
            info1,
            "altitude",
        )

        vertical_speed = info_float(
            info1,
            "vertical_speed",
        )

        vn = info_float(
            info1,
            "vn",
            0.0,
        )

        ve = info_float(
            info1,
            "ve",
            0.0,
        )

        horizontal_speed = float(
            np.hypot(
                vn,
                ve,
            )
        )

        drift = info_float(
            info1,
            "drift",
            999.0,
        )

        stable = bool(
            295.0
            <=
            altitude
            <=
            305.0
            and
            abs(
                vertical_speed
            )
            <=
            0.50
            and
            horizontal_speed
            <=
            1.0
            and
            drift
            <=
            3.0
        )

        stable_time = (
            stable_time
            +
            dt1
            if stable
            else
            0.0
        )

        if (
            stable_time
            >=
            HANDOFF_STABLE_TIME
        ):
            break

        if (
            terminated
            and
            not bool(
                info1.get(
                    "success",
                    False,
                )
            )
        ):
            env1.close()

            raise RuntimeError(
                "Stage 1 failed before stable handoff."
            )

        if truncated:
            env1.close()

            raise RuntimeError(
                "Stage 1 truncated before stable handoff."
            )

    if (
        stable_time
        <
        HANDOFF_STABLE_TIME
    ):
        env1.close()

        raise RuntimeError(
            "Stable Stage-1 handoff was not reached."
        )

    # Mission geometry origin is the true Stage-1 hover handoff.
    lat0 = latitude_deg(
        fdm
    )

    lon0 = longitude_deg(
        fdm
    )

    sim_time_before_attach = first_finite(
        fdm,
        [
            "simulation/sim-time-sec",
        ],
    )

    env2 = (
        HelicopterEnvStage2RefineMapped(
            aileron_scale=
                AILERON_SCALE,

            rudder_scale=
                RUDDER_SCALE,
        )
    )

    # Disposable reset initializes Python bookkeeping only.
    env2.reset()

    env2.fdm = (
        fdm
    )

    if hasattr(
        env2,
        "forward_distance",
    ):
        env2.forward_distance = (
            0.0
        )

    if hasattr(
        env2,
        "target_heading",
    ):
        env2.target_heading = float(
            mission_heading
        )

    for attr in [
        "steps",
        "target_hold_steps",
        "hold_steps",
        "success_hold_steps",
    ]:
        if hasattr(
            env2,
            attr,
        ):
            setattr(
                env2,
                attr,
                0,
            )

    if (
        id(
            get_fdm(
                env2
            )
        )
        !=
        active_fdm_id
    ):
        env2.fdm = None
        env1.close()

        raise RuntimeError(
            "FDM continuity failed."
        )

    sim_time_after_attach = first_finite(
        fdm,
        [
            "simulation/sim-time-sec",
        ],
    )

    if (
        np.isfinite(
            sim_time_before_attach
        )
        and
        np.isfinite(
            sim_time_after_attach
        )
        and
        abs(
            sim_time_after_attach
            -
            sim_time_before_attach
        )
        >
        1e-9
    ):
        env2.fdm = None
        env1.close()

        raise RuntimeError(
            "Simulation clock changed during Stage-2 attach."
        )

    obs2 = np.asarray(
        env2._get_obs(),
        dtype=np.float32,
    )

    dt2 = env_control_dt(
        env2
    )

    for _ in range(
        int(
            STAGE2_MAX_TIME
            /
            dt2
        )
    ):
        action2, _ = (
            stage2_model.predict(
                obs2,
                deterministic=True,
            )
        )

        action2 = np.asarray(
            action2,
            dtype=np.float32,
        ).reshape(
            -1
        )

        (
            obs2,
            _,
            terminated,
            truncated,
            info2,
        ) = env2.step(
            action2
        )

        obs2 = np.asarray(
            obs2,
            dtype=np.float32,
        )

        forward, _cross = geometry(
            fdm,
            lat0,
            lon0,
            mission_heading,
        )

        if (
            forward
            >=
            STAGE3_TAKEOVER_FORWARD_FT
        ):
            if hasattr(
                env2,
                "forward_distance",
            ):
                env2.forward_distance = float(
                    forward
                )

            break

        if (
            terminated
            and
            not bool(
                info2.get(
                    "success",
                    False,
                )
            )
        ):
            env2.fdm = None
            env1.close()

            raise RuntimeError(
                "Stage 2 failed before Stage-3 takeover."
            )

        if truncated:
            env2.fdm = None
            env1.close()

            raise RuntimeError(
                "Stage 2 truncated before Stage-3 takeover."
            )

    state = snapshot(
        fdm,
        lat0,
        lon0,
        mission_heading,
    )

    return {
        "env1":
            env1,

        "env2":
            env2,

        "fdm":
            fdm,

        "stage2_obs":
            obs2,

        "lat0":
            lat0,

        "lon0":
            lon0,

        "mission_heading":
            mission_heading,

        "active_fdm_id":
            active_fdm_id,

        "state":
            state,
    }


