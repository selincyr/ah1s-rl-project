# LOCKED TEACHER ACTION
# =====================================================================

def locked_teacher_action(
    stage2_obs,
    state,
):
    base_action, _ = (
        stage2_model.predict(
            stage2_obs,
            deterministic=True,
        )
    )

    base_action = np.asarray(
        base_action,
        dtype=np.float32,
    ).reshape(
        -1
    )

    action = (
        base_action.copy()
    )

    # Altitude teacher.
    altitude_error = (
        TARGET_ALT_FT
        -
        state[
            "altitude_ft"
        ]
    )

    collective_correction = (
        COLLECTIVE_BIAS
        +
        ALT_KP
        *
        altitude_error
        -
        VS_KD
        *
        state[
            "vertical_speed_fps"
        ]
    )

    collective_correction = float(
        np.clip(
            collective_correction,
            -MAX_ALT_CORR,
            +MAX_ALT_CORR,
        )
    )

    action[0] = float(
        np.clip(
            base_action[0]
            +
            collective_correction,
            -1.0,
            +1.0,
        )
    )

    # Longitudinal endpoint teacher.
    v_des = float(
        np.clip(
            K_POS
            *
            (
                state[
                    "position_error_ft"
                ]
                -
                BRAKE_LEAD_FT
            ),
            -V_REV_MAX,
            +V_FWD_MAX,
        )
    )

    speed_error = (
        state[
            "forward_speed_fps"
        ]
        -
        v_des
    )

    elevator_residual = (
        -KV
        *
        speed_error
        +
        Q_DAMP
        *
        state[
            "pitch_rate_rad_s"
        ]
    )

    elevator_residual = float(
        np.clip(
            elevator_residual,
            -MAX_ELEVATOR_RESIDUAL,
            +MAX_ELEVATOR_RESIDUAL,
        )
    )

    action[1] = float(
        np.clip(
            ELEVATOR_TRIM_ACTION
            +
            elevator_residual,
            -1.0,
            +1.0,
        )
    )

    # Data-grounded lateral teacher.
    lateral_active = bool(
        state[
            "forward_ft"
        ]
        >=
        LATERAL_ENABLE_FORWARD_FT
    )

    if lateral_active:
        lateral_correction = (
            -LATERAL_KP
            *
            state[
                "cross_track_ft"
            ]
            -
            LATERAL_KD
            *
            state[
                "lateral_speed_fps"
            ]
        )

        action[2] = float(
            np.clip(
                HOVER_TRIM
                +
                lateral_correction,
                IDENTIFIED_A2_MIN,
                IDENTIFIED_A2_MAX,
            )
        )

    else:
        action[2] = (
            CRUISE_AILERON_ACTION
        )

    action[3] = (
        RUDDER_ACTION
    )

    return np.clip(
        action,
        -1.0,
        +1.0,
    ).astype(
        np.float32
    )


