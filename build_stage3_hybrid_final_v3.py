def stage3_observation(
    state,
):
    """
    Dedicated Stage-3 observation.

    It includes the mission geometry that the endpoint controller actually
    needs. All entries are scaled to approximately O(1).
    """

    obs = np.array(
        [
            # 0 altitude error
            (
                state[
                    "altitude_ft"
                ]
                -
                TARGET_ALT_FT
            )
            /
            10.0,

            # 1 vertical speed
            state[
                "vertical_speed_fps"
            ]
            /
            5.0,

            # 2 forward position error
            state[
                "position_error_ft"
            ]
            /
            250.0,

            # 3 forward speed
            state[
                "forward_speed_fps"
            ]
            /
            12.0,

            # 4 cross-track
            state[
                "cross_track_ft"
            ]
            /
            10.0,

            # 5 lateral speed
            state[
                "lateral_speed_fps"
            ]
            /
            5.0,

            # 6-7 continuous heading representation
            math.sin(
                state[
                    "heading_error_rad"
                ]
            ),

            math.cos(
                state[
                    "heading_error_rad"
                ]
            ),

            # 8 pitch
            state[
                "pitch_rad"
            ]
            /
            0.20,

            # 9 roll
            state[
                "roll_rad"
            ]
            /
            0.20,

            # 10 roll rate
            state[
                "roll_rate_rad_s"
            ]
            /
            1.0,

            # 11 pitch rate
            state[
                "pitch_rate_rad_s"
            ]
            /
            1.0,

            # 12 yaw rate
            state[
                "yaw_rate_rad_s"
            ]
            /
            1.0,

            # 13 rotor RPM
            state[
                "rotor_rpm"
            ]
            /
            400.0,
        ],
        dtype=np.float32,
    )

    return np.clip(
        obs,
        -10.0,
        +10.0,
    ).astype(
        np.float32
    )


def safety_reason(
    state,
):
    if (
        state[
            "altitude_ft"
        ]
        <
        ALT_SAFE_MIN
    ):
        return (
            "altitude_below_safe"
        )

    if (
        state[
            "altitude_ft"
        ]
        >
        ALT_SAFE_MAX
    ):
        return (
            "altitude_above_safe"
        )

    if (
        abs(
            math.degrees(
                state[
                    "pitch_rad"
                ]
            )
        )
        >
        MAX_ABS_PITCH_DEG
    ):
        return (
            "pitch_limit"
        )

    if (
        abs(
            math.degrees(
                state[
                    "roll_rad"
                ]
            )
        )
        >
        MAX_ABS_ROLL_DEG
    ):
        return (
            "roll_limit"
        )

    if (
        abs(
            state[
                "cross_track_ft"
            ]
        )
        >
        MAX_CROSS_SAFE_FT
    ):
        return (
            "cross_track_safety_limit"
        )

    return ""


