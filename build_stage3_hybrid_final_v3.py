"""
AH-1S / JSBSim
STAGE 3 HYBRID FINAL BUILD V3
=============================

Method
------
1) Use the already locked Stage-1 neural policy.
2) Use the already locked Stage-2 HYBRID FINAL neural policy.
3) Reproduce the true continuous Stage1 -> Stage2 -> Stage3 handoff.
4) Reproduce the locked Stage-3 teacher:
      - unchanged altitude controller
      - unchanged longitudinal endpoint controller
      - data-grounded lateral controller
5) Build a dedicated Stage-3 observation that includes the mission geometry
   actually required by the teacher (forward position error and cross-track).
6) Collect teacher state-action data, including small off-trajectory recovery
   samples generated by perturbing the APPLIED action while keeping the
   teacher label exact.
7) Behavior-clone the complete four-action teacher into a fresh PPO actor.
8) Validate the BC policy with teacher OFF on a fresh true continuous flight.
9) Fine-tune the BC policy with genuine reward-based PPO updates in a
   dedicated Stage-3 environment; no teacher/controller is used at runtime.
10) Validate each RL candidate teacher OFF on the true continuous
    Stage1 -> Stage2 -> Stage3 JSBSim mission.
11) Save only a passing PPO-refined Stage-3 model.

Important terminology
---------------------
- Behavior cloning / distillation is supervised policy learning, NOT RL.
- The later PPO .learn(...) phase IS reward-based reinforcement learning.
- The final model is accepted only if the runtime teacher is OFF.

The Stage-3 model is intentionally a separate policy from Stage 2 because
Stage 3 is a different control phase and requires endpoint geometry in its
observation.
"""

