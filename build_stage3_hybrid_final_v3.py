# STAGE-3 TRAINING ENVIRONMENT
# =====================================================================

class HelicopterEnvStage3Hybrid(
    gym.Env
):
    """
    Dedicated Stage-3 environment.

    reset():
        physically reproduces the locked Stage1 -> Stage2 flight and returns
        the true Stage-3 start at ~80 ft forward.

    step(action):
        applies the four neural actions directly through the mapped Stage-2
        actuator path, advances the SAME JSBSim FDM, computes a mission reward,
        and terminates only on Stage-3 success/failure.

    No teacher/controller is used in step().
    """

    metadata = {
        "render_modes": [],
    }

    def __init__(
        self,
    ):
        super().__init__()

        self.action_space = (
            spaces.Box(
                low=-1.0,
                high=+1.0,
                shape=(
                    4,
                ),
                dtype=np.float32,
            )
        )

        self.observation_space = (
            spaces.Box(
                low=np.full(
                    14,
                    -10.0,
                    dtype=np.float32,
                ),
                high=np.full(
                    14,
                    +10.0,
                    dtype=np.float32,
                ),
                dtype=np.float32,
            )
        )

        self.env1 = None
        self.env2 = None
        self.fdm = None

        self.stage2_obs = None

        self.lat0 = None
        self.lon0 = None
        self.mission_heading = None

        self.dt = (
            DEFAULT_CONTROL_DT
        )

        self.steps = 0
        self.max_steps = int(
            STAGE3_MAX_TIME
            /
            self.dt
        )

        self.hover_hold_s = 0.0

        self.previous_abs_position_error = None
        self.previous_action = np.zeros(
            4,
            dtype=np.float32,
        )

        self.last_state = None

    def _close_current(
        self,
    ):
        if self.env2 is not None:
            try:
                self.env2.fdm = None
            except Exception:
                pass

        if self.env1 is not None:
            try:
                self.env1.close()
            except Exception:
                pass

        self.env1 = None
        self.env2 = None
        self.fdm = None
        self.stage2_obs = None

    def reset(
        self,
        seed=None,
        options=None,
    ):
        super().reset(
            seed=seed,
        )

        self._close_current()

        start = build_stage3_start()

        self.env1 = start[
            "env1"
        ]

        self.env2 = start[
            "env2"
        ]

        self.fdm = start[
            "fdm"
        ]

        self.stage2_obs = np.asarray(
            start[
                "stage2_obs"
            ],
            dtype=np.float32,
        )

        self.lat0 = float(
            start[
                "lat0"
            ]
        )

        self.lon0 = float(
            start[
                "lon0"
            ]
        )

        self.mission_heading = float(
            start[
                "mission_heading"
            ]
        )

        self.dt = env_control_dt(
            self.env2
        )

        self.max_steps = int(
            STAGE3_MAX_TIME
            /
            self.dt
        )

        self.steps = 0
        self.hover_hold_s = 0.0

        self.previous_action = np.zeros(
            4,
            dtype=np.float32,
        )

        state = snapshot(
            self.fdm,
            self.lat0,
            self.lon0,
            self.mission_heading,
        )

        self.last_state = (
            state.copy()
        )

        self.previous_abs_position_error = abs(
            state[
                "position_error_ft"
            ]
        )

        return (
            stage3_observation(
                state
            ),
            self._info(
                state,
                success=False,
                termination_reason="",
            ),
        )

    def _apply_action(
        self,
        action,
    ):
        action = np.asarray(
            action,
            dtype=np.float32,
        ).reshape(
            -1
        )

        action = np.clip(
            action,
            -1.0,
            +1.0,
        ).astype(
            np.float32
        )

        # Use the repaired actuator mapping.
        self.env2._apply_action(
            action
        )

        for _ in range(
            physics_steps(
                self.env2
            )
        ):
            if not self.fdm.run():
                raise RuntimeError(
                    "JSBSim stopped during Stage-3 training."
                )

        if hasattr(
            self.env2,
            "previous_action",
        ):
            try:
                self.env2.previous_action = (
                    action.copy()
                )
            except Exception:
                pass

        if hasattr(
            self.env2,
            "steps",
        ):
            try:
                self.env2.steps += 1
            except Exception:
                pass

        # IMPORTANT:
        # Do not refresh Stage-2 observation here. The original locked
        # Stage-3 V3 loop first updates env2.forward_distance from the TRUE
        # inertial mission geometry, then calls _get_obs(). Reversing that
        # order leaves Stage-2 bookkeeping stale and changes the neural
        # base action used by the teacher.
        return action

    def _info(
        self,
        state,
        success,
        termination_reason,
    ):
        return {
            "success":
                bool(
                    success
                ),

            "termination_reason":
                str(
                    termination_reason
                ),

            "forward_ft":
                float(
                    state[
                        "forward_ft"
                    ]
                ),

            "position_error_ft":
                float(
                    state[
                        "position_error_ft"
                    ]
                ),

            "forward_speed_fps":
                float(
                    state[
                        "forward_speed_fps"
                    ]
                ),

            "cross_track_ft":
                float(
                    state[
                        "cross_track_ft"
                    ]
                ),

            "lateral_speed_fps":
                float(
                    state[
                        "lateral_speed_fps"
                    ]
                ),

            "altitude_ft":
                float(
                    state[
                        "altitude_ft"
                    ]
                ),

            "vertical_speed_fps":
                float(
                    state[
                        "vertical_speed_fps"
                    ]
                ),

            "heading_error_deg":
                float(
                    state[
                        "heading_error_deg"
                    ]
                ),

            "hover_hold_s":
                float(
                    self.hover_hold_s
                ),

            "physical_aileron_cmd":
                float(
                    state[
                        "physical_aileron_cmd"
                    ]
                ),
        }

    def step(
        self,
        action,
    ):
        used_action = self._apply_action(
            action
        )

        self.steps += 1

        state = snapshot(
            self.fdm,
            self.lat0,
            self.lon0,
            self.mission_heading,
        )

        self.last_state = (
            state.copy()
        )

        # Reproduce the exact bookkeeping order used by the already
        # validated Stage-3 V3 teacher:
        #
        #   raw_cycle(...)
        #   snapshot(...)
        #   env2.forward_distance = true inertial forward position
        #   env2.steps += 1
        #   obs2 = env2._get_obs()
        #
        # env2.steps was already incremented in _apply_action(); the missing
        # forward-distance update was the reproduction bug in the first
        # build_stage3_hybrid_final.py.
        if hasattr(
            self.env2,
            "forward_distance",
        ):
            self.env2.forward_distance = float(
                state[
                    "forward_ft"
                ]
            )

        self.stage2_obs = np.asarray(
            self.env2._get_obs(),
            dtype=np.float32,
        )

        abs_position_error = abs(
            state[
                "position_error_ft"
            ]
        )

        position_improvement = (
            self.previous_abs_position_error
            -
            abs_position_error
        )

        self.previous_abs_position_error = (
            abs_position_error
        )

        # -------------------------------------------------------------
        # REWARD — mission objective only; no runtime teacher action.
        # -------------------------------------------------------------

        reward = 0.0

        # Progress toward the endpoint.
        reward += (
            4.0
            *
            position_improvement
        )

        # Position error.
        reward -= (
            0.025
            *
            abs_position_error
        )

        # Speed should decay as the endpoint approaches.
        desired_speed_for_reward = float(
            np.clip(
                K_POS
                *
                (
                    state[
                        "position_error_ft"
                    ]
                    -
                    BRAKE_LEAD_FT
                ),
                -V_REV_MAX,
                +V_FWD_MAX,
            )
        )

        reward -= (
            1.50
            *
            abs(
                state[
                    "forward_speed_fps"
                ]
                -
                desired_speed_for_reward
            )
        )

        # Lateral geometry.
        reward -= (
            1.25
            *
            abs(
                state[
                    "cross_track_ft"
                ]
            )
        )

        reward -= (
            1.75
            *
            abs(
                state[
                    "lateral_speed_fps"
                ]
            )
        )

        # Altitude / vertical motion.
        reward -= (
            0.80
            *
            abs(
                state[
                    "altitude_ft"
                ]
                -
                TARGET_ALT_FT
            )
        )

        reward -= (
            1.50
            *
            abs(
                state[
                    "vertical_speed_fps"
                ]
            )
        )

        # Heading / attitude.
        reward -= (
            0.10
            *
            abs(
                state[
                    "heading_error_deg"
                ]
            )
        )

        reward -= (
            0.10
            *
            abs(
                math.degrees(
                    state[
                        "pitch_rad"
                    ]
                )
            )
        )

        reward -= (
            0.10
            *
            abs(
                math.degrees(
                    state[
                        "roll_rad"
                    ]
                )
            )
        )

        # Small smoothness term.
        reward -= (
            0.05
            *
            float(
                np.mean(
                    (
                        used_action
                        -
                        self.previous_action
                    )
                    **
                    2
                )
            )
        )

        self.previous_action = (
            used_action.copy()
        )

        hover_now = endpoint_hover_now(
            state
        )

        self.hover_hold_s = (
            self.hover_hold_s
            +
            self.dt
            if hover_now
            else
            0.0
        )

        # Dense endpoint bonus.
        if endpoint_stop_now(
            state
        ):
            reward += 6.0

        if endpoint_lateral_now(
            state
        ):
            reward += 3.0

        if (
            ALT_MIN
            <=
            state[
                "altitude_ft"
            ]
            <=
            ALT_MAX
        ):
            reward += 1.0

        if hover_now:
            reward += 15.0

        terminated = False
        truncated = False
        success = False
        termination_reason = ""

        reason = safety_reason(
            state
        )

        if reason:
            reward -= 300.0
            terminated = True
            termination_reason = (
                reason
            )

        elif (
            self.hover_hold_s
            >=
            STOP_HOLD_SECONDS
        ):
            reward += 500.0
            terminated = True
            success = True
            termination_reason = (
                "endpoint_hover_5s"
            )

        elif (
            self.steps
            >=
            self.max_steps
        ):
            truncated = True
            termination_reason = (
                "stage3_time_limit"
            )

        return (
            stage3_observation(
                state
            ),
            float(
                reward
            ),
            bool(
                terminated
            ),
            bool(
                truncated
            ),
            self._info(
                state,
                success,
                termination_reason,
            ),
        )

    def close(
        self,
    ):
        self._close_current()


